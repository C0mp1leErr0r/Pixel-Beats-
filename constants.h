// ============================================================================
// constants.h - 游戏核心常量定义
// ============================================================================
// 本文件定义游戏中使用的所有常量，包括窗口尺寸、游戏规则、音频参数等
// 包含枚举类型定义
// ============================================================================

#ifndef CONSTANTS_H
#define CONSTANTS_H

// ============================================================================
// 窗口和布局常量
// ============================================================================
// 【说明】这些常量定义了游戏的视觉布局，包括窗口大小、轨道数量、判定线位置等
// 【使用场景】在绘制和游戏逻辑中广泛使用，用于计算音符位置、碰撞检测等

#define SCREEN_WIDTH 800          // 窗口宽度（像素）- 游戏设计基于800像素宽度
#define SCREEN_HEIGHT 600         // 窗口高度（像素）- 游戏设计基于600像素高度
#define LANE_COUNT 4              // 轨道数量（四轨道下落式）- 对应键盘D/F/J/K四个按键
#define LANE_WIDTH (SCREEN_WIDTH / LANE_COUNT)  // 单轨道宽度（200像素）
#define JUDGE_LINE_Y (SCREEN_HEIGHT - 100)      // 判定线Y坐标（500像素处）- 音符到达此线时判定
#define NOTE_SIZE 60              // 音符大小（40x40像素）- 音符为正方形

// ============================================================================
// 音符下落速度常量
// ============================================================================
// 【说明】定义了音符的基础下落速度
// 【计算原理】
//   - NOTE_SPEED = 8 表示每帧下落8像素
//   - 在60FPS下：8 × 60 = 480像素/秒
//   - 音符从顶部(0)到判定线(500)需要约1秒
// 【速度调整】
//   - 实际速度 = NOTE_SPEED × noteSpeed（用户设置的速度倍率）
//   - noteSpeed可以在设置中调整（0.5x - 2.0x）
// ============================================================================
#define NOTE_SPEED 12

// ============================================================================
// 判定系统时间窗口（毫秒）
// ============================================================================
// 【说明】定义了击中判定的精确度窗口，越小越精确
// 【计算公式】
//   - missThreshold = GOOD_TIME × speed × 60 / 1000
//   - 音符超过判定线超过此阈值仍未被击中，判定为MISS
// 【判定标准】（以标准速度1.0x为例）
//   - PERFECT_TIME = 50ms：最精确的判定，得1000分
//   - GREAT_TIME = 100ms：良好判定，得500分
//   - GOOD_TIME = 120ms：基本判定，得100分
//   - 超过GOOD_TIME：MISS，连击中断，得0分

#define PERFECT_TIME 50
#define GREAT_TIME 100
#define GOOD_TIME 120

// ============================================================================
// 粒子系统常量
// ============================================================================
// 【说明】粒子系统用于游戏中的视觉反馈效果
// 【MAX_PARTICLES】最大粒子数量
//   - 粒子是击中音符时产生的爆炸效果
//   - 需要足够数量以产生良好的视觉效果，但也不能太多以影响性能
// ============================================================================
#define MAX_PARTICLES 200          // 最大粒子数量

// ============================================================================
// 音频参数常量
// ============================================================================
// 【AUDIO_SAMPLE_RATE】音频采样率
//   - 44100Hz是CD质量的采样率
//   - 用于程序化生成击中音效
// 【HIT_SOUND_DURATION】击中音效时长（秒）
//   - 0.05秒 = 50毫秒
//   - 短暂的按键音反馈

#define AUDIO_SAMPLE_RATE 44100   // 音频采样率（Hz）
#define HIT_SOUND_DURATION 0.05f   // 击中音效时长（秒）

// ============================================================================
// 枚举类型定义
// ============================================================================
// 【Difficulty】难度等级枚举
//   - 用于区分不同难度谱面文件
//   - 与谱面文件名对应：_easy.txt, _normal.txt, _hard.txt
//   - 影响音符密度和下落速度
enum class Difficulty { EASY, NORMAL, HARD };

// 【JudgmentType】判定类型枚举
//   - 用于记录玩家的击中精度
//   - PERFECT：完美判定（时间差≤50ms）
//   - GREAT：良好判定（50ms<时间差≤100ms）
//   - GOOD：基本判定（100ms<时间差≤120ms）
//   - MISS：未击中或时间差过大
enum class JudgmentType { PERFECT, GREAT, GOOD, MISS };

// 【MenuState】菜单状态枚举
//   - 用于控制游戏的状态流转
//   - MAIN：主菜单界面
//   - SELECT_MUSIC：音乐选择界面
//   - SELECT_DIFFICULTY：难度选择界面
//   - EDITOR：谱面编辑器界面
//   - SETTINGS：设置界面
enum class MenuState { MAIN, SELECT_MUSIC, SELECT_DIFFICULTY, EDITOR, SETTINGS };

#endif // CONSTANTS_H
