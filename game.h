// ============================================================================
// game.h - 游戏核心逻辑声明
// ============================================================================
// 本模块处理核心游戏逻辑：
//   - 游戏状态更新（UpdateGame）
//   - 音符判定（CheckNote）
//   - 输入处理（HandleInput）
// ============================================================================
// 【模块关系】
//   - game.cpp实现游戏核心逻辑
//   - 被main.cpp中的游戏主循环调用
//   - 依赖effects.h中的特效生成函数
//   - 依赖audio.h中的音效播放函数
//   - 依赖structs.h中的Chart、GameState结构体
//   - 依赖constants.h中的判定时间常量等
// ============================================================================

#ifndef GAME_H
#define GAME_H

#include "raylib.h"
#include "constants.h"
#include "structs.h"

// ============================================================================
// 游戏主循环
// ============================================================================

// 更新游戏状态（每帧调用）
// 【功能】游戏主循环的核心函数，每帧调用一次更新游戏中所有元素状态
// 【参数】
//   - chart: 谱面引用，包含所有音符信息
//   - gameState: 游戏状态引用，记录分数、连击等
//   - music: 音乐引用，用于检测音乐是否结束
//   - deltaTime: 距离上一帧的时间（秒），用于平滑动画
// 【实现步骤】
//   1. 更新屏幕震动效果和按键状态
//   2. 更新视觉特效和粒子系统
//   3. 遍历所有音符，更新下落位置并检测漏接（MISS）
//   4. 检查游戏结束条件并处理结束逻辑
void UpdateGame(Chart& chart, GameState& gameState, Music* music, float deltaTime);

// ============================================================================
// 判定系统
// ============================================================================
// 【功能说明】检测玩家是否成功击中音符
// 【判定标准】
//   - PERFECT: 时间差<=50ms，得1000分
//   - GREAT: 50ms<时间差<=100ms，得500分
//   - GOOD: 100ms<时间差<=120ms，得100分
//   - MISS: 时间差>120ms或音符已过判定线，得0分

// 检查玩家是否成功击中音符
// 【功能】判定系统的核心函数，检查玩家按键是否成功击中音符
// 【参数】
//   - chart: 谱面引用
//   - gameState: 游戏状态引用
//   - lane: 轨道号（0-3）
// 【实现步骤】
//   1. 在指定轨道上找到距离判定线最近的未判定音符
//   2. 计算按键时间与音符时间的时间差（毫秒）
//   3. 根据时间差判断命中精度
//   4. 如果命中：增加分数、增加连击、标记音符、生成特效、播放音效
// 【关键算法】
//   - 距离计算：distance = abs(note.y - JUDGE_LINE_Y)
//   - 时间差转换：timeDiff = distance / speed * 1000 / 60
void CheckNote(Chart& chart, GameState& gameState, int lane);

// ============================================================================
// 输入处理
// ============================================================================

// 处理玩家按键输入
// 【功能】检测玩家的按键输入，调用CheckNote进行判定
// 【参数】
//   - chart: 谱面引用
//   - gameState: 游戏状态引用
// 【实现步骤】
//   1. 使用static数组keyDown[4]记录按键状态，防止重复触发
//   2. 检测D/F/J/K四个按键的状态
//   3. 如果按键刚按下，调用CheckNote检测该轨道
//   4. 检测暂停按键（P或ESCAPE键）
// 【关键算法】
//   - 使用static变量确保数组在函数调用之间保持状态
//   - 按键检测：if (pressed && !keyDown[i]) 防止按住键时重复触发
void HandleInput(Chart& chart, GameState& gameState);

// ============================================================================
// 画面震动
// ============================================================================

// 更新画面震动状态
// 【功能】每帧递减屏幕震动强度，实现震动衰减效果
// 【参数】gameState: 游戏状态引用
// 【关键算法】
//   - 震动衰减：screenShake *= 0.9（每帧变为90%）
//   - 震动归零：当screenShake < 0.5时重置为0
void UpdateScreenShake(GameState& gameState);

// 更新按键状态
// 【功能】更新GameState中的keyPressed数组，记录四个按键的当前状态
// 【参数】gameState: 游戏状态引用
// 【使用场景】用于UI绘制时显示按键是否被按下（按键高亮效果）
void UpdateKeyPressStates(GameState& gameState);

// ============================================================================
// 分数计算
// ============================================================================

// 根据准确率计算评级
// 【功能】根据游戏结束时的准确率计算最终评级
// 【参数】accuracy: 准确率（0.0-100.0）
// 【返回值】评级字符（S/A/B/C/D）
// 【评级规则】
//   - S级: 准确率>=95%
//   - A级: 准确率>=90%
//   - B级: 准确率>=80%
//   - C级: 准确率>=70%
//   - D级: 准确率<70%
char GetGrade(float accuracy);

#endif // GAME_H
